// Slugify une catégorie (accents supprimés, espaces → tirets)
export function categoryToSlug(category) {
  return category
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/\s+/g, '-');
}

// Récupérer les articles d'une catégorie (par slug)
export function getArticlesByCategorySlug(slug) {
  return articles.filter(a => categoryToSlug(a.category) === slug);
}

