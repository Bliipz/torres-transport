export function getRelatedArticles(currentArticle, limit = 3) {
  const tags = new Set(currentArticle.tags || []);
  const cat = currentArticle.category;
  return articles
    .filter((a) => a.slug !== currentArticle.slug)
    .map((a) => {
      const sharedTags = (a.tags || []).filter((t) => tags.has(t)).length;
      const sameCat = a.category === cat ? 2 : 0;
      return { article: a, score: sharedTags * 3 + sameCat };
    })
    .sort((x, y) => {
      if (y.score !== x.score) return y.score - x.score;
      return new Date(y.article.date).getTime() - new Date(x.article.date).getTime();
    })
    .slice(0, limit)
    .map((s) => s.article);
}

// Mapping tags → villes pour le maillage interne
